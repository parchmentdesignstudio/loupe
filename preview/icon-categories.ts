/** The names given, grouped by category in that order, with any in no group last under Other */
export function byCategory(names: IconName[]): [string, IconName[]][] {
	const given = new Set(names);
	const placed = new Set(iconCategories.flatMap(([, members]) => members));
	const groups = iconCategories.map(([name, members]): [string, IconName[]] => [name, members.filter((member) => given.has(member))]);
	const other = names.filter((name) => !placed.has(name));
	return [...groups, ['Other', other] as [string, IconName[]]].filter(([, members]) => members.length > 0);
}
